scores_len = {"0-4k": [], "4-8k": [], "8-32k": [], "32k+": []}

def scorer(dataset, predictions, answers, lengths, all_classes):
    total_score = 0.
    for (prediction, ground_truths, length) in zip(predictions, answers, lengths):
        score = 0.
        if prediction:
            if dataset in ["trec", "triviaqa", "samsum", "lsht"]:
                prediction = prediction.lstrip('\n').split('\n')[0]
            for ground_truth in ground_truths:
                score = max(score, dataset2metric[dataset](prediction, ground_truth, all_classes=all_classes))
        # print(f"dataset={dataset} score={score} pred={prediction} gt={ground_truths}")
        total_score += score
        if length < 4 * 1024:
            scores_len["0-4k"].append(score)
        elif length < 8 * 1024:
            scores_len["4-8k"].append(score)
        elif length < 32 * 1024:
            scores_len["8-32k"].append(score)
        else:
            scores_len["32k+"].append(score)
    if len(predictions) == 0: return None
    return round(100 * total_score / len(predictions), 2)

