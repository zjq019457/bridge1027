def rep(a, b):
    global t
    n = t.count(a)
    if n != 1:
        sys.exit(f"rep: found {n}x: {a[:60]}")
    t = t.replace(a, b)


def span(start, end, new):
    global t
    if t.count(start) != 1:
        sys.exit(f"span start found {t.count(start)}x: {start[:60]}")
    i = t.index(start)
    j = t.index(end, i) + len(end)
    t = t[:i] + new + t[j:]


